"""Freeze absolute import names so module loading never interns them in RAM."""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "src/feuristic"
DESTINATION = PACKAGE / "_qstr_names.py"


def modules():
    result = {"feuristic._qstr_names"}
    for path in PACKAGE.rglob("*.py"):
        parts = list(path.relative_to(PACKAGE.parent).with_suffix("").parts)
        if parts[-1] == "__init__":
            parts.pop()
        result.add(".".join(parts))
    return sorted(result)


def render():
    lines = [
        "# SPDX-License-Identifier: GPL-3.0-only",
        "# Copyright (C) 2026 The feuristic contributors",
        "# Generated by tools/generate_frozen_qstr.py. Do not edit.",
        '"""Import identifiers in frozen ROM. This function is never called."""',
        "# ruff: noqa: F401, F811, I001, PLW0406",
        "# fmt: off",
        "",
        "",
        "def _frozen_names():",
    ]
    for name in modules():
        lines.append("    import " + name)
        if "." in name:
            parent, leaf = name.rsplit(".", 1)
            lines.append("    from " + parent + " import " + leaf)
    # MicroPython interns single-character string indexing (e.g. Base45).
    # Keep each literal in bytecode rather than folding them into one string.
    for code in range(32, 127):
        lines.append("    _character = " + repr(chr(code)))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_text() != expected:
            parser.exit(1, "Frozen import names are stale; run tools/generate_frozen_qstr.py\n")
    else:
        DESTINATION.write_text(expected)
    print(str(len(modules())) + " frozen module identifiers")


if __name__ == "__main__":
    main()
