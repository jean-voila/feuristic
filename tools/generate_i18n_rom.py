"""Generate frozen translation constants without importing application modules.

Edit application STRINGS tables, then run this command. --check verifies that
all firmware translations match those host tables exactly.
"""

from __future__ import annotations

import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = (
    "apps/backup/strings.py",
    "apps/card/aes/strings.py",
    "apps/card/openpgp/strings.py",
    "apps/card/piv/strings.py",
    "apps/fido2/strings.py",
    "apps/importer/strings.py",
    "apps/otp/strings.py",
    "apps/timesync/strings.py",
    "ui/strings.py",
    "ui/strings_apps.py",
    "ui/strings_backup.py",
)
DESTINATION = ROOT / "src/feuristic/core/_i18n_rom.py"


def translations() -> dict:
    result = {}
    for source in SOURCES:
        tree = ast.parse((ROOT / "src/feuristic" / source).read_text())
        assignments = [
            node
            for node in tree.body
            if isinstance(node, ast.Assign)
            and any(isinstance(target, ast.Name) and target.id == "STRINGS" for target in node.targets)
        ]
        if len(assignments) != 1:
            raise ValueError("expected one literal STRINGS table: " + source)
        table = ast.literal_eval(assignments[0].value)
        for key, value in table.items():
            if not isinstance(key, str) or not isinstance(value, tuple) or len(value) != 2:
                raise ValueError("invalid translation: " + source)
            if not all(isinstance(text, str) for text in value):
                raise ValueError("invalid translation value: " + key)
            if key in result and result[key] != value:
                raise ValueError("conflicting translation: " + key)
            result[key] = value
    return result


def render() -> str:
    lines = [
        "# SPDX-License-Identifier: GPL-3.0-only",
        "# Copyright (C) 2026 The feuristic contributors",
        "# Generated by tools/generate_i18n_rom.py. Edit the application STRINGS tables.",
        '"""Sorted immutable translations; tuples and strings remain in frozen ROM."""',
        "",
        "# fmt: off",
        "# ruff: noqa: E501",
        "TABLE = (",
    ]
    for key, value in sorted(translations().items()):
        lines.append("    " + repr((key, value)) + ",")
    return "\n".join([*lines, ")", ""])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_text() != generated:
            parser.exit(1, "Frozen translations are stale; run tools/generate_i18n_rom.py\n")
    else:
        DESTINATION.write_text(generated)
    print(str(len(translations())) + " frozen translation keys")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
