"""OpenPGP RSA-2048 compatibility profile.

Private-key operations are tested with a key generated by ``cryptography``
and injected into the identity (no dependency on ``feuristic.core.rsa``).
On-card generation needs ``feuristic.core.rsa`` and is skipped without it.
"""

import pytest
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import padding, rsa

from feuristic.apps.card.openpgp import const as pgp
from feuristic.apps.card.openpgp import keys as alg
from feuristic.apps.card.openpgp import localmgmt
from feuristic.core.errors import InvalidInput

from ...aio import run
from .conftest import Env, public_from_7f49

SHA256_DI_PREFIX = bytes.fromhex("3031300d060960864801650304020105000420")

_KEY = rsa.generate_private_key(public_exponent=65537, key_size=2048)


def _secret(key=_KEY):
    nums = key.private_numbers()
    return nums.p.to_bytes(128, "big") + nums.q.to_bytes(128, "big")


def inject(e, role, key=_KEY):
    slot = e.store.ident.keys[role]
    slot.attr = pgp.ATTR_RSA2048
    slot.set_secret(_secret(key), pgp.ORIGIN_GENERATED)
    e.store.save()


@pytest.fixture
def renv():
    e = Env()
    for role in pgp.ROLES:
        if role != pgp.DEC:
            inject(e, role)
    inject(e, pgp.DEC)
    e.select()
    return e


def test_public_key_do(renv):
    data, sw = renv.read_public(0xB6)
    assert sw == 0x9000
    do = public_from_7f49(data)
    assert int.from_bytes(do[0x81], "big") == _KEY.public_key().public_numbers().n
    assert do[0x82] == b"\x01\x00\x01"
    assert len(do[0x81]) == 256


def test_rsa_signature_pkcs1(renv):
    import hashlib

    digest = hashlib.sha256(b"hello").digest()
    renv.verify(0x81, b"123456")
    sig, sw = renv.tx(0x2A, 0x9E, 0x9A, SHA256_DI_PREFIX + digest, ne=65536)
    assert sw == 0x9000 and len(sig) == 256
    _KEY.public_key().verify(sig, b"hello", padding.PKCS1v15(), hashes.SHA256())
    assert dict(renv.ui.prompts[-1].fields)["openpgp.field.type"] == "RSA PKCS#1 v1.5 signature"
    assert renv.tx(0x2A, 0x9E, 0x9A, bytes(103), ne=65536)[1] == 0x6700


def test_rsa_decipher(renv):
    ct = _KEY.public_key().encrypt(b"\x09" + bytes(range(32)) + b"\x00\x01", padding.PKCS1v15())
    renv.verify(0x82, b"123456")
    pt, sw = renv.tx(0x2A, 0x80, 0x86, b"\x00" + ct, ne=65536)
    assert sw == 0x9000 and pt == b"\x09" + bytes(range(32)) + b"\x00\x01"
    assert renv.tx(0x2A, 0x80, 0x86, b"\x02" + ct, ne=65536)[1] == 0x6A80
    assert renv.tx(0x2A, 0x80, 0x86, ct, ne=65536)[1] == 0x6700
    # garbage cryptogram: bad padding → 6A80, no detail
    bad = (int.from_bytes(ct, "big") ^ 1).to_bytes(256, "big")
    assert renv.tx(0x2A, 0x80, 0x86, b"\x00" + bad, ne=65536)[1] == 0x6A80


def test_rsa_internal_authenticate(renv):
    import hashlib

    digest = hashlib.sha256(b"ssh").digest()
    renv.verify(0x82, b"123456")
    sig, sw = renv.tx(0x88, 0, 0, SHA256_DI_PREFIX + digest, ne=65536)
    assert sw == 0x9000
    _KEY.public_key().verify(sig, b"ssh", padding.PKCS1v15(), hashes.SHA256())


def test_rsa_identity_persists(renv):
    renv.reboot().select()
    data, _ = renv.read_public(0xB8)
    assert int.from_bytes(public_from_7f49(data)[0x81], "big") == _KEY.public_key().public_numbers().n


def test_rsa_v4_fingerprint_body():
    n = _KEY.public_key().public_numbers().n.to_bytes(256, "big")
    body = alg.v4_public_body(pgp.KIND_RSA2048, n, 1_800_000_000)
    assert body[5] == 1 and body[6:8] == b"\x08\x00" and body[8:264] == n
    assert body[264:] == b"\x00\x11\x01\x00\x01"


def test_pkcs1_helpers():
    em = alg.pkcs1v15_sign_pad(b"\xaa" * 51, 256)
    assert em[:2] == b"\x00\x01" and em[-52:] == b"\x00" + b"\xaa" * 51
    with pytest.raises(InvalidInput):
        alg.pkcs1v15_sign_pad(bytes(246), 256)
    good = b"\x00\x02" + b"\x11" * 8 + b"\x00" + b"msg"
    assert alg.pkcs1v15_decrypt_unpad(good) == b"msg"
    for bad in (
        b"\x00\x02" + b"\x11" * 7 + b"\x00" + b"msg",  # padding too short
        b"\x00\x01" + b"\x11" * 8 + b"\x00" + b"msg",
        b"\x01\x02" + b"\x11" * 8 + b"\x00" + b"msg",
        b"\x00\x02" + b"\x11" * 12,  # no separator
    ):
        with pytest.raises(InvalidInput):
            alg.pkcs1v15_decrypt_unpad(bad)


def test_check_secret():
    alg.check_secret(pgp.KIND_RSA2048, _secret())
    with pytest.raises(InvalidInput):
        alg.check_secret(pgp.KIND_RSA2048, bytes(256))
    with pytest.raises(InvalidInput):
        alg.check_secret(pgp.KIND_RSA2048, _secret()[:200])
    small = rsa.generate_private_key(public_exponent=65537, key_size=1024)
    nums = small.private_numbers()
    with pytest.raises(InvalidInput):
        alg.check_secret(pgp.KIND_RSA2048, nums.p.to_bytes(128, "big") + nums.q.to_bytes(128, "big"))


# --- generation (needs feuristic.core.rsa) ---------------------------------------------

needs_core_rsa = pytest.mark.skipif(
    not alg.rsa_available(), reason="feuristic.core.rsa not available (RSA keygen is a separate work item)"
)


@needs_core_rsa
def test_rsa_generation_on_card():
    e = Env()
    e.select()
    e.admin()
    assert e.put(0xC1, pgp.ATTR_RSA2048) == 0x9000
    data, sw = e.generate(0xB6)
    assert sw == 0x9000
    n = public_from_7f49(data)[0x81]
    assert len(n) == 256 and n[0] & 0x80
    e.verify(0x81, b"123456")
    import hashlib

    sig, sw = e.tx(0x2A, 0x9E, 0x9A, SHA256_DI_PREFIX + hashlib.sha256(b"x").digest(), ne=65536)
    assert sw == 0x9000
    pub = rsa.RSAPublicNumbers(65537, int.from_bytes(n, "big")).public_key()
    pub.verify(sig, b"x", padding.PKCS1v15(), hashes.SHA256())


@needs_core_rsa
def test_rsa_local_profile():
    e = Env()
    fprs = run(localmgmt.generate_keys(e.store, localmgmt.PROFILE_RSA2048, 1_800_000_000))
    assert len(fprs) == 3
    assert e.store.ident.keys[1].attr == pgp.ATTR_RSA2048


class _FakeRsaModule:
    """Stand-in for feuristic.core.rsa: async generate() returning RsaKey."""

    def __init__(self):
        self.calls = []

    async def generate(self, bits=2048, e=65537, progress=None, yield_fn=None):
        from feuristic.platform import crypto

        self.calls.append((bits, e, progress, yield_fn))
        nums = _KEY.private_numbers()
        return crypto.RsaKey(nums.p.to_bytes(128, "big"), nums.q.to_bytes(128, "big"), e)


def test_rsa_generate_path_with_stand_in_module(monkeypatch):
    fake = _FakeRsaModule()
    monkeypatch.setattr(alg, "rsa_module", lambda: fake)
    marker = object()
    e = Env()
    e.applet.rsa_yield = marker
    e.select()
    e.admin()
    assert e.put(0xC2, b"\x01\x08\x00\x00\x11\x00") == 0x9000
    data, sw = e.generate(0xB8)
    assert sw == 0x9000
    assert int.from_bytes(public_from_7f49(data)[0x81], "big") == _KEY.public_key().public_numbers().n
    assert fake.calls == [(2048, 65537, None, marker)]
    fprs = run(localmgmt.generate_keys(e.store, localmgmt.PROFILE_RSA2048, 1_800_000_000))
    assert len(fprs) == 3 and len(fake.calls) == 4
