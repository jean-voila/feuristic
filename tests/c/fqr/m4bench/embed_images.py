"""Embed PBM corpus images into a C header for the bare-metal benchmark.

usage: embed_images.py out.h vector_dir name[:both] ...
"""

import pathlib
import sys


def load_pbm(path: pathlib.Path):
    data = path.read_bytes()
    assert data[:2] == b"P4"
    fields, pos = [], 2
    while len(fields) < 2:
        while data[pos : pos + 1].isspace():
            pos += 1
        if data[pos : pos + 1] == b"#":
            pos = data.index(b"\n", pos) + 1
            continue
        start = pos
        while data[pos : pos + 1].isdigit():
            pos += 1
        fields.append(int(data[start:pos]))
    pos += 1
    w, h = fields
    return w, h, data[pos : pos + ((w + 7) // 8) * h]


def main() -> int:
    out, vdir, names = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), sys.argv[3:]
    lines = [
        "/* generated by embed_images.py */",
        "#include <stdint.h>",
        "typedef struct { const char *name; const uint8_t *data; uint32_t w, h; int both; } bench_image_t;",
    ]
    entries = []
    for i, spec in enumerate(names):
        name, _, opt = spec.partition(":")
        w, h, px = load_pbm(vdir / f"{name}.pbm")
        lines.append(f"static const uint8_t img{i}[{len(px)}] = {{")
        for k in range(0, len(px), 24):
            lines.append("  " + ",".join(str(b) for b in px[k : k + 24]) + ",")
        lines.append("};")
        entries.append(f'  {{"{name} ({w}x{h})", img{i}, {w}, {h}, {1 if opt == "both" else 0}}},')
    lines.append("static const bench_image_t bench_images[] = {")
    lines += entries
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
