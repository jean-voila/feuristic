"""Generate frsa_sieve_table.h: the product of the first 2048 odd primes.

    python3 lib/frsa/gen_sieve_table.py > lib/frsa/frsa_sieve_table.h

The host backend (src/feuristic/platform/_host_crypto.py) recomputes the
same product, so both implementations of ``rsa_sieve`` agree bit for bit.
"""

import sys

COUNT = 2048


def odd_primes(count: int) -> list:
    limit = 32
    while True:
        sieve = bytearray([1]) * limit
        sieve[0] = sieve[1] = 0
        i = 2
        while i * i < limit:
            if sieve[i]:
                sieve[i * i :: i] = bytearray(len(sieve[i * i :: i]))
            i += 1
        primes = [p for p in range(3, limit) if sieve[p]]
        if len(primes) >= count:
            return primes[:count]
        limit *= 2


def main() -> None:
    primes = odd_primes(COUNT)
    product = 1
    for p in primes:
        product *= p
    data = product.to_bytes((product.bit_length() + 7) // 8, "big")
    out = sys.stdout
    out.write("// SPDX-License-Identifier: GPL-3.0-only\n")
    out.write("// Copyright (C) 2026 The feuristic contributors\n")
    out.write("//\n// GENERATED by lib/frsa/gen_sieve_table.py -- do not edit.\n")
    out.write(f"// Product of the first {COUNT} odd primes (3 .. {primes[-1]}),\n")
    out.write(f"// {product.bit_length()} bits, big-endian.\n\n")
    out.write("#ifndef FRSA_SIEVE_TABLE_H\n#define FRSA_SIEVE_TABLE_H\n\n")
    out.write(f"#define FRSA_SIEVE_PRIME_COUNT {COUNT}\n")
    out.write(f"#define FRSA_SIEVE_LARGEST_PRIME {primes[-1]}\n\n")
    out.write(f"static const unsigned char FRSA_SIEVE_PRODUCT[{len(data)}] = {{\n")
    for i in range(0, len(data), 12):
        chunk = ", ".join(f"0x{b:02X}" for b in data[i : i + 12])
        out.write(f"    {chunk},\n")
    out.write("};\n\n#endif  // FRSA_SIEVE_TABLE_H\n")


if __name__ == "__main__":
    main()
