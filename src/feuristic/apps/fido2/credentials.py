"""FIDO2 credentials: discoverable records, wrapped credential IDs, U2F key handles.

Three credential ID formats exist (first byte = format version):

``0x01`` — discoverable credential (13 bytes)::

    0x01 | uid(8) | seq(4, big-endian)

  ``uid`` is the random :class:`~feuristic.core.store.RecordStore` uid of the
  record in namespace ``FIDO_CREDS``; ``seq`` the creation sequence number.
  Re-registering the same (rpId, user.id) keeps the uid (atomic copy-on-write
  replacement, CTAP 2.1 §6.1.2 step 17) but gets a new ``seq``, so the old
  credential ID stops matching. A lookup succeeds only if the record exists,
  its ``seq`` matches and ``SHA-256(rpId)`` equals the request's rpIdHash.

``0x02`` — non-discoverable credential (62 bytes)::

    0x02 | nonce(12) | AES-256-GCM(info(1) | privateKey(32)) | tag(16)

  key = ``kdf(ms, "fido2/cred-wrap", context=seed)``, AAD = ``0x02 | rpIdHash``
  (binds the credential to its RP; any bit flip or a different RP fails the
  tag check). ``info`` carries the algorithm, credProtect level and the
  hmac-secret flag.

``0x03`` — U2F key handle (61 bytes, see :mod:`.ctap1`)::

    0x03 | nonce(12) | AES-256-GCM(privateKey(32)) | tag(16)

  key = ``kdf(ms, "fido2/u2f-wrap", context=seed)``, AAD = ``0x03 | appParam``.

``seed`` is the reset epoch of :mod:`.state` (regenerated by
authenticatorReset). Private keys are random (P-256 scalars or Ed25519
seeds), never derived from the master secret, so discoverable credentials
can be exported by the QR backup and restored on another device.

Per-credential secrets — ``CredRandomWithUV`` / ``CredRandomWithoutUV``
(hmac-secret, CTAP 2.1 §12.5) and ``largeBlobKey`` (§12.3) — are derived
with HKDF from the **credential private key** using the KDF labels
``fido2/cred-random`` and ``fido2/largeblob-key``: they need no storage and
survive a backup/restore, keeping hmac-secret outputs and encrypted
largeBlob entries usable on the restored device.

Discoverable record payload (canonical CBOR map, ≤ 384 bytes,
docs/architecture.md §6.3)::

    {1: seq, 2: rpId (≤ 128 B), 3: user.id (≤ 64 B), ?4: user.name (≤ 64 B),
     ?5: user.displayName (≤ 64 B), 6: info, 7: privateKey(32)}

Record header flag bit 0 = BS (backup state, WebAuthn L3 §6.1): set once
the credential was exported to a QR backup or restored from one. Every
discoverable credential is backup eligible (BE = 1).
"""

