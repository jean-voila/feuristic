class CredentialStore:
    """Discoverable credential storage plus credential ID (un)wrapping.

    A packed 4,400-byte RAM index of ``(uid, rpIdHash, seq)`` is built lazily
    from the records and kept in sync by every write.
    """

    def __init__(self, state, ms: bytes) -> None:
        self.state = state
        self._ms = ms
        self.records = RecordStore(namespaces.FIDO_CREDS, CAPACITY, MAX_PAYLOAD, RECORD_TYPE)
        self._index = None
        self._next_seq = 1
        self._wrap_key = None
        self._u2f_key = None

    # -- keys --------------------------------------------------------------
    def _cred_wrap_key(self) -> bytes:
        if self._wrap_key is None:
            self._wrap_key = kdf.derive(self._ms, b"fido2/cred-wrap", 32, self.state.seed)
        return self._wrap_key

    def _u2f_wrap_key(self) -> bytes:
        if self._u2f_key is None:
            self._u2f_key = kdf.derive(self._ms, b"fido2/u2f-wrap", 32, self.state.seed)
        return self._u2f_key

    def forget_keys(self) -> None:
        """Drop cached wrapping keys (after a reset changed the seed)."""
        self._wrap_key = None
        self._u2f_key = None

    # -- index -------------------------------------------------------------
    def _build_index(self) -> CredentialIndex:
        if self._index is not None:
            return self._index
        index = CredentialIndex(CAPACITY)
        owners = {}  # SHA-256(rpIdHash || user.id) -> (position, generation)
        max_seq = 0
        for uid in self.records.uids():
            try:
                rec = self.records.get_record(uid)
                cred = decode_record(uid, rec.payload, rec.flags)
            except MemoryError:
                raise
            except Exception as e:  # corrupt record: never fatal
                log.warning(__name__, "skipping corrupt credential record: %s", repr(e))
                continue
            # The temporary rebuild index must not retain every maximum-length
            # user ID alongside its RP hash. The fixed 32-byte prefix makes
            # this encoding unambiguous; verify any hit before deleting data.
            owner = crypto.sha256(cred.rp_id_hash + cred.user_id)
            prev = owners.get(owner)
            if prev is not None:
                previous = self._load(index[prev[0]][0])
                if (
                    previous is None
                    or previous.rp_id_hash != cred.rp_id_hash
                    or previous.user_id != cred.user_id
                ):
                    raise StorageCorrupted("credential owner digest collision")
                # interrupted overwrite (restore): keep the newest version
                if rec.generation > prev[1]:
                    self.records.delete(index[prev[0]][0])
                    index[prev[0]] = (uid, cred.rp_id_hash, cred.seq)
                    owners[owner] = (prev[0], rec.generation)
                else:
                    self.records.delete(uid)
                max_seq = max(max_seq, cred.seq)
                continue
            owners[owner] = (len(index), rec.generation)
            index.append((uid, cred.rp_id_hash, cred.seq))
            max_seq = max(max_seq, cred.seq)
        self._index = index
        self._next_seq = max_seq + 1
        return index

    def invalidate(self) -> None:
        self._index = None

    def count(self) -> int:
        return len(self._build_index())

    def remaining(self) -> int:
        return max(0, CAPACITY - self.count())

    def is_full(self) -> bool:
        return self.count() >= CAPACITY

    def uids(self) -> list:
        return [e[0] for e in self._build_index()]

    def get(self, uid: bytes):
        """Credential for ``uid`` or ``None``."""
        uid = bytes(uid)
        for e in self._build_index():
            if e[0] == uid:
                return self._load(uid)
        return None

    def _load(self, uid: bytes):
        try:
            rec = self.records.get_record(uid)
            return decode_record(uid, rec.payload, rec.flags)
        except MemoryError:
            raise
        except Exception:
            return None

    def for_rp(self, rp_id_hash: bytes) -> CredentialSelection:
        """Discoverable credentials, newest first, without retaining every key."""
        out = CredentialSelection(self, rp_id_hash)
        for uid, _h, _seq in self._build_index().matching(rp_id_hash):
            credential = self._load(uid)
            if credential is not None:
                out.append(credential)
        return out

    def find_user(self, rp_id_hash: bytes, user_id: bytes):
        # Registration needs only an equality search, without sorting or
        # allocating an ID list for every existing account of the service.
        for uid, h, _seq in self._build_index():
            if h == rp_id_hash:
                credential = self._load(uid)
                if credential is not None and crypto.ct_equal(credential.user_id, user_id):
                    return credential
        return None

    def rps(self) -> list:
        """``[(rpId, rpIdHash, count)]`` sorted by rpId."""
        seen = {}
        for uid, h, _seq in self._build_index():
            entry = seen.get(h)
            if entry is None:
                c = self._load(uid)
                if c is None:
                    continue
                seen[h] = [c.rp_id, h, 1]
            else:
                entry[2] += 1
        out = [tuple(v) for v in seen.values()]
        out.sort(key=lambda t: t[0])
        return out

    # -- writes ------------------------------------------------------------
    def _put(self, cred: Credential) -> None:
        payload = encode_record(cred)
        flags = RECORD_FLAG_BS if cred.backup_state else 0
        self.records.put(cred.uid, payload, flags)
        index = self._build_index()
        for i in range(len(index)):
            if index[i][0] == cred.uid:
                index[i] = (cred.uid, cred.rp_id_hash, cred.seq)
                break
        else:
            index.append((cred.uid, cred.rp_id_hash, cred.seq))
        if cred.seq >= self._next_seq:
            self._next_seq = cred.seq + 1

    def create_resident(
        self,
        rp_id: str,
        user_id: bytes,
        user_name,
        display_name,
        alg: int,
        key: bytes,
        cred_protect: int,
        hmac_secret: bool,
        large_blob: bool,
    ) -> Credential:
        """Store a new discoverable credential, atomically replacing any
        credential with the same (rpId, user.id). Raises ``StorageFull``."""
        if len(rp_id.encode()) > MAX_RP_ID_LEN or len(user_id) > MAX_USER_ID_LEN:
            raise InvalidInput("credential field too long")
        rp_id_hash = crypto.sha256(rp_id.encode())
        old = self.find_user(rp_id_hash, user_id)
        if old is None and self.is_full():
            raise StorageFull("key store full")
        uid = old.uid if old is not None else self._new_uid()
        seq = self._next_seq
        if seq > 0xFFFFFFFF:  # pragma: no cover - 4 billion registrations
            raise StorageFull("sequence exhausted")
        cred = Credential(
            KIND_RESIDENT,
            bytes((ID_RESIDENT,)) + uid + seq.to_bytes(4, "big"),
            rp_id_hash,
            key,
            alg,
            cred_protect,
            hmac_secret,
            large_blob,
            rp_id,
            user_id,
            user_name or None,
            display_name or None,
            seq,
            uid,
            False,
        )
        self._put(cred)
        return cred

    def restore(self, cred: Credential, replace_uid=None) -> None:
        """Write a restored credential (keeps its credential ID). If
        ``replace_uid`` names a *different* record (same rpId+user.id), it is
        deleted after the new one is durable (duplicates left by a power cut
        are resolved at the next index build, newest generation wins)."""
        self._build_index()
        other = replace_uid if replace_uid is not None and replace_uid != cred.uid else None
        if cred.uid not in self.records and self.is_full():
            if other is None:
                raise StorageFull("key store full")
            # RecordStore only keeps a spare slot for same-uid replacements
            self.delete(other)
            other = None
        self._put(cred)
        if other is not None:
            self.delete(other)

    def update_user(self, cred: Credential, user_name, display_name) -> Credential:
        cred.user_name = user_name or None
        cred.display_name = display_name or None
        self._put(cred)
        return cred

    def set_backup_state(self, uid: bytes) -> bool:
        cred = self.get(uid)
        if cred is None:
            return False
        if not cred.backup_state:
            cred.backup_state = True
            self._put(cred)
        return True

    def delete(self, uid: bytes) -> bool:
        uid = bytes(uid)
        ok = self.records.delete(uid)
        if self._index is not None:
            self._index.remove_uid(uid)
        return ok

    def wipe(self) -> None:
        self.records.wipe()
        if self._index is not None:
            self._index.clear()
        self._next_seq = 1
        self.forget_keys()

    def _new_uid(self) -> bytes:
        while True:
            uid = crypto.random_bytes(8)
            if uid not in self.records:
                return uid

    # -- non-discoverable credentials ------------------------------------------
    def wrap(
        self, rp_id_hash: bytes, alg: int, key: bytes, cred_protect: int, hmac_secret: bool
    ) -> Credential:
        """Create the credential ID of a non-discoverable credential."""
        info = encode_info(alg, cred_protect, hmac_secret, False)
        nonce = crypto.random_bytes(12)
        aad = bytes((ID_WRAPPED,)) + rp_id_hash
        ct, tag = crypto.aes256_gcm_encrypt(self._cred_wrap_key(), nonce, bytes((info,)) + key, aad)
        cred_id = bytes((ID_WRAPPED,)) + nonce + ct + tag
        return Credential(KIND_WRAPPED, cred_id, rp_id_hash, key, alg, cred_protect, hmac_secret)

    def _unwrap(self, cred_id: bytes, rp_id_hash: bytes):
        aad = bytes((ID_WRAPPED,)) + rp_id_hash
        try:
            pt = crypto.aes256_gcm_decrypt(
                self._cred_wrap_key(), cred_id[1:13], cred_id[13:46], cred_id[46:62], aad
            )
            alg, prot, hmac_secret, _ = decode_info(pt[0])
        except Exception:
            return None
        return Credential(KIND_WRAPPED, bytes(cred_id), rp_id_hash, bytes(pt[1:33]), alg, prot, hmac_secret)

    def u2f_wrap(self, app_param: bytes, key: bytes) -> bytes:
        nonce = crypto.random_bytes(12)
        ct, tag = crypto.aes256_gcm_encrypt(self._u2f_wrap_key(), nonce, key, bytes((ID_U2F,)) + app_param)
        return bytes((ID_U2F,)) + nonce + ct + tag

    def u2f_unwrap(self, key_handle: bytes, app_param: bytes):
        """Private key of a U2F key handle bound to ``app_param`` or ``None``."""
        if len(key_handle) != U2F_KH_LEN or key_handle[0] != ID_U2F:
            return None
        try:
            key = crypto.aes256_gcm_decrypt(
                self._u2f_wrap_key(),
                key_handle[1:13],
                key_handle[13:45],
                key_handle[45:61],
                bytes((ID_U2F,)) + app_param,
            )
        except Exception:
            return None
        k = int.from_bytes(key, "big")
        if not 0 < k < crypto.P256_ORDER:
            return None
        return bytes(key)

    # -- lookup ----------------------------------------------------------------
    def lookup(self, cred_id: bytes, rp_id_hash: bytes):
        """Credential with ID ``cred_id`` bound to ``rp_id_hash`` or ``None``."""
        n = len(cred_id)
        if n == 0 or n > MAX_CRED_ID_LEN:
            return None
        v = cred_id[0]
        if v == ID_RESIDENT and n == RESIDENT_ID_LEN:
            cred = self.get(cred_id[1:9])
            if cred is None or not crypto.ct_equal(cred.cred_id, cred_id):
                return None
            if not crypto.ct_equal(cred.rp_id_hash, rp_id_hash):
                return None
            return cred
        if v == ID_WRAPPED and n == WRAPPED_ID_LEN:
            return self._unwrap(cred_id, rp_id_hash)
        if v == ID_U2F and n == U2F_KH_LEN:
            key = self.u2f_unwrap(cred_id, rp_id_hash)
            if key is None:
                return None
            return Credential(KIND_U2F, bytes(cred_id), rp_id_hash, key)
        return None

    def lookup_resident(self, cred_id: bytes):
        """Discoverable credential by ID regardless of RP (credMgmt)."""
        if len(cred_id) != RESIDENT_ID_LEN or cred_id[0] != ID_RESIDENT:
            return None
        cred = self.get(cred_id[1:9])
        if cred is None or not crypto.ct_equal(cred.cred_id, cred_id):
            return None
        return cred


def check_storage_error(exc) -> bool:
    """True if ``exc`` means persistent storage could not take the write."""
    return isinstance(exc, (StorageFull, StorageCorrupted))
