def encode_record(cred: Credential) -> bytes:
    m = {
        _K_SEQ: cred.seq,
        _K_RP_ID: cred.rp_id,
        _K_USER_ID: cred.user_id,
        _K_INFO: cred.info(),
        _K_KEY: cred.key,
    }
    if cred.user_name:
        m[_K_USER_NAME] = cred.user_name
    if cred.display_name:
        m[_K_DISPLAY] = cred.display_name
    return cbor.encode(m)


def _opt_text(m: dict, k: int, cap: int):
    v = m.get(k)
    if v is None:
        return None
    if not isinstance(v, str) or len(v.encode()) > cap:
        raise InvalidInput("record text")
    return v


def decode_record(uid: bytes, payload: bytes, flags: int) -> Credential:
    """Strictly decode a record payload (raises InvalidInput / CborError)."""
    m = cbor.decode(payload, max_depth=1, max_items=32, canonical=True)
    if not isinstance(m, dict):
        raise InvalidInput("record")
    for k in m:
        if not isinstance(k, int) or isinstance(k, bool) or not _K_SEQ <= k <= _K_KEY:
            raise InvalidInput("record key")
    seq = m.get(_K_SEQ)
    rp_id = m.get(_K_RP_ID)
    user_id = m.get(_K_USER_ID)
    key = m.get(_K_KEY)
    if not isinstance(seq, int) or isinstance(seq, bool) or not 0 <= seq <= 0xFFFFFFFF:
        raise InvalidInput("record seq")
    if not isinstance(rp_id, str) or not 0 < len(rp_id.encode()) <= MAX_RP_ID_LEN:
        raise InvalidInput("record rpId")
    if not isinstance(user_id, bytes) or len(user_id) > MAX_USER_ID_LEN:
        raise InvalidInput("record user.id")
    if not isinstance(key, bytes) or len(key) != 32:
        raise InvalidInput("record key")
    alg, prot, hmac_secret, large_blob = decode_info(m.get(_K_INFO))
    return Credential(
        KIND_RESIDENT,
        bytes((ID_RESIDENT,)) + uid + seq.to_bytes(4, "big"),
        crypto.sha256(rp_id.encode()),
        key,
        alg,
        prot,
        hmac_secret,
        large_blob,
        rp_id,
        user_id,
        _opt_text(m, _K_USER_NAME, MAX_NAME_LEN),
        _opt_text(m, _K_DISPLAY, MAX_NAME_LEN),
        seq,
        uid,
        bool(flags & RECORD_FLAG_BS),
    )


