ALG_ES256 = const(-7)
ALG_EDDSA = const(-8)
SUPPORTED_ALGS = (ALG_ES256, ALG_EDDSA)

KIND_RESIDENT = const(1)
KIND_WRAPPED = const(2)
KIND_U2F = const(3)

ID_RESIDENT = const(0x01)
ID_WRAPPED = const(0x02)
ID_U2F = const(0x03)
RESIDENT_ID_LEN = const(13)
WRAPPED_ID_LEN = const(62)
U2F_KH_LEN = const(61)
MAX_CRED_ID_LEN = const(64)

CAPACITY = const(100)  # product spec §5: 100 discoverable credentials
MAX_PAYLOAD = const(384)  # docs/architecture.md §6.3
RECORD_TYPE = const(0x46)
RECORD_FLAG_BS = const(0x01)

MAX_RP_ID_LEN = const(128)
MAX_USER_ID_LEN = const(64)
MAX_NAME_LEN = const(64)

PROTECT_UV_OPTIONAL = const(1)
PROTECT_UV_OPTIONAL_WITH_LIST = const(2)
PROTECT_UV_REQUIRED = const(3)

_INFO_PROTECT_MASK = const(0x03)
_INFO_HMAC_SECRET = const(0x04)
_INFO_LARGE_BLOB = const(0x08)
_INFO_EDDSA = const(0x10)
_INFO_KNOWN = const(0x1F)

_K_SEQ = const(1)
_K_RP_ID = const(2)
_K_USER_ID = const(3)
_K_USER_NAME = const(4)
_K_DISPLAY = const(5)
_K_INFO = const(6)
_K_KEY = const(7)


def encode_info(alg: int, cred_protect: int, hmac_secret: bool, large_blob: bool) -> int:
    info = cred_protect & _INFO_PROTECT_MASK
    if hmac_secret:
        info |= _INFO_HMAC_SECRET
    if large_blob:
        info |= _INFO_LARGE_BLOB
    if alg == ALG_EDDSA:
        info |= _INFO_EDDSA
    return info


def decode_info(info: int) -> tuple:
    """Return ``(alg, cred_protect, hmac_secret, large_blob)`` or raise."""
    if not isinstance(info, int) or isinstance(info, bool) or info & ~_INFO_KNOWN:
        raise InvalidInput("credential info")
    prot = info & _INFO_PROTECT_MASK
    if prot == 0:
        raise InvalidInput("credProtect")
    alg = ALG_EDDSA if info & _INFO_EDDSA else ALG_ES256
    return alg, prot, bool(info & _INFO_HMAC_SECRET), bool(info & _INFO_LARGE_BLOB)


def generate_key(alg: int) -> bytes:
    """Fresh random private key for ``alg`` (strong RNG)."""
    if alg == ALG_ES256:
        return crypto.p256_generate()
    if alg == ALG_EDDSA:
        return crypto.random_bytes(32)
    raise InvalidInput("algorithm")


def public_key_raw(alg: int, key: bytes) -> bytes:
    if alg == ALG_ES256:
        return crypto.p256_public(key)
    return crypto.ed25519_public(key)


def cose_key(alg: int, pub: bytes) -> dict:
    """COSE_Key of a credential public key (RFC 9053 §7; CTAP 2.1 §6.5.6)."""
    if alg == ALG_ES256:
        return {1: 2, 3: ALG_ES256, -1: 1, -2: pub[1:33], -3: pub[33:65]}
    return {1: 1, 3: ALG_EDDSA, -1: 6, -2: pub}


class CredentialSelection:
    """Small credential IDs with a single key decoded only when requested."""

    def __init__(self, store, rp_id_hash, ids=None):
        self.store = store
        self.rp_id_hash = rp_id_hash
        self.ids = [] if ids is None else ids

    def append(self, credential):
        self.ids.append(credential.cred_id)

    def __len__(self):
        return len(self.ids)

    def __getitem__(self, index):
        if isinstance(index, slice):
            return CredentialSelection(self.store, self.rp_id_hash, self.ids[index])
        return self.store.lookup(self.ids[index], self.rp_id_hash)

    def __iter__(self):
        for cid in self.ids:
            credential = self.store.lookup(cid, self.rp_id_hash)
            if credential is not None:
                yield credential

    def labels(self):
        return _CredentialLabels(self)


class _CredentialLabels:
    def __init__(self, credentials):
        self.credentials = credentials

    def __len__(self):
        return len(self.credentials)

    def __getitem__(self, index):
        if isinstance(index, slice):
            return [credential.label() for credential in self.credentials[index]]
        credential = self.credentials[index]
        return "-" if credential is None else credential.label()


class Credential:
    """A usable credential (decoded record, unwrapped ID or U2F key handle)."""

    def __init__(
        self,
        kind: int,
        cred_id: bytes,
        rp_id_hash: bytes,
        key: bytes,
        alg: int = ALG_ES256,
        cred_protect: int = PROTECT_UV_OPTIONAL,
        hmac_secret: bool = False,
        large_blob: bool = False,
        rp_id=None,
        user_id=None,
        user_name=None,
        display_name=None,
        seq: int = 0,
        uid=None,
        backup_state: bool = False,
    ) -> None:
        self.kind = kind
        self.cred_id = cred_id
        self.rp_id_hash = rp_id_hash
        self.key = key
        self.alg = alg
        self.cred_protect = cred_protect
        self.hmac_secret = hmac_secret
        self.large_blob = large_blob
        self.rp_id = rp_id
        self.user_id = user_id
        self.user_name = user_name
        self.display_name = display_name
        self.seq = seq
        self.uid = uid
        self.backup_state = backup_state

    @property
    def discoverable(self) -> bool:
        return self.kind == KIND_RESIDENT

    @property
    def backup_eligible(self) -> bool:
        """WebAuthn L3 BE flag: discoverable credentials can be exported by
        the QR backup (product spec §5, §8.2), non-discoverable ones cannot."""
        return self.kind == KIND_RESIDENT

    def info(self) -> int:
        return encode_info(self.alg, self.cred_protect, self.hmac_secret, self.large_blob)

    def public_key(self) -> bytes:
        return public_key_raw(self.alg, self.key)

    def cose_public_key(self) -> dict:
        return cose_key(self.alg, self.public_key())

    def fingerprint(self) -> str:
        """Short hex fingerprint of the public key (menus, backup)."""
        return crypto.sha256(self.public_key())[:8].hex()

    def sign(self, message: bytes) -> bytes:
        """WebAuthn signature: DER ECDSA over SHA-256 (ES256) or PureEdDSA."""
        if self.alg == ALG_ES256:
            return crypto.ecdsa_sig_to_der(crypto.p256_sign_digest(self.key, crypto.sha256(message)))
        return crypto.ed25519_sign(self.key, message)

    def cred_random(self, uv: bool) -> bytes:
        """CredRandomWithUV / CredRandomWithoutUV (CTAP 2.1 §12.5)."""
        return kdf.derive(self.key, b"fido2/cred-random", 32, b"uv" if uv else b"no-uv")

    def large_blob_key(self):
        """largeBlobKey (CTAP 2.1 §12.3) or ``None`` if not requested at creation."""
        if not self.large_blob:
            return None
        return kdf.derive(self.key, b"fido2/largeblob-key", 32)

    def label(self) -> str:
        """Account name shown on the device."""
        if self.user_name:
            return self.user_name
        if self.display_name:
            return self.display_name
        if self.user_id:
            return self.user_id[:8].hex()
        return "-"


